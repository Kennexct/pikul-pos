// Builds db/neon-setup.sql: every migration in db/migrations, in order, as one file to paste into the Neon SQL Editor
// (ADR-022). All statements are idempotent, so running it again on an existing database is safe.
// Usage: node scripts/db-setup.mjs   (npm test checks that the file is up to date)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'db', 'migrations');

export function neonSetupSql() {
  const files = fs.readdirSync(dir).filter((f) => /^\d{3}_.+\.sql$/.test(f)).sort();
  const parts = files.map((f) => `-- ===== ${f} =====\n${fs.readFileSync(path.join(dir, f), 'utf8').trim()}\n`);
  return [
    '-- Pikul — full database setup for a fresh Neon project (generated by scripts/db-setup.mjs; do not edit by hand).',
    `-- Contains: ${files.join(', ')}. Safe to run more than once.`,
    '-- Neon console → your project → SQL Editor → paste all of this → Run.',
    'begin;',
    '',
    ...parts,
    'commit;',
    '',
    '-- Check: should list accounts, account_grants, admin_audit, admin_sessions, campaigns, images, login_codes,',
    '-- merchant_daily, payments, plans, rate_events, refresh_tokens, site_content.',
    "select table_name from information_schema.tables where table_schema = 'public' order by table_name;",
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  fs.writeFileSync(path.join(root, 'db', 'neon-setup.sql'), neonSetupSql());
  console.log('Wrote db/neon-setup.sql');
}
